// Bundles everything in public/ into src/assets.gen.js so the Worker serves the pages itself.
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, extname } from 'node:path';

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.json': 'application/json',
};
const root = 'public';
const files = {};
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (TYPES[extname(p)]) files['/' + relative(root, p).split('\\').join('/')] = { type: TYPES[extname(p)], body: readFileSync(p, 'utf8') };
  }
})(root);
writeFileSync('src/assets.gen.js', '// Generated by scripts/build-assets.mjs. Do not edit.\nexport default ' + JSON.stringify(files) + ';\n');
console.log(`Bundled ${Object.keys(files).length} files into src/assets.gen.js`);
